// Maps a Place channel/reservation/review URL field (website_url, whatsapp_url,
// x_url, google_maps_url, uber_eats_url, …) onto a ChannelKey so the place
// detail Channels row can render a brand mark. Fields without a brand mark
// (resy_url, didi_food_url, phone) return null — the caller falls back to a
// lucide glyph, exactly as web falls back to the lucide `Icon`.
export function channelKeyForField(field: string): ChannelKey | null {
  switch (field) {
    case 'website_url':
      return 'website';
    case 'whatsapp_url':
      return 'whatsapp';
    case 'instagram_url':
      return 'instagram';
    case 'facebook_url':
      return 'facebook';
    case 'x_url':
      return 'x';
    case 'threads_url':
      return 'threads';
    case 'reddit_url':
      return 'reddit';
    case 'opentable_url':
      return 'opentable';
    case 'uber_eats_url':
      return 'ubereats';
    case 'google_maps_url':
      return 'googlemaps';
    default:
      return null;
  }
}
