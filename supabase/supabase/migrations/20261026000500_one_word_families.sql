insert into public.catalog_membership (slug, family_keys)
select slug, keys from membership_seed
on conflict (slug) do update set family_keys = excluded.family_keys;

delete from public.catalog_membership m
 where not exists (select 1 from membership_seed s where s.slug = m.slug)
   and exists (select 1 from public.place_categories c where c.slug = m.slug);

do $$
declare
  seeded int;
  matched int;
begin
  select count(*) into seeded from membership_seed;
  select count(*) into matched
    from membership_seed s
    join public.catalog_membership m
      on m.slug = s.slug and m.family_keys = s.keys;
  if seeded <> 478 or matched <> seeded then
    raise exception 'catalog_membership matches % of % seeded Table A rows (expected 478)', matched, seeded;
  end if;
end;
$$;

