--      atlas_family_slugs_valid never sees a key that is not a family yet.
--   3. tacos and japanese go only after no row holds them; the seed call
--      deletes them and renumbers the twenty.
-- No app_config write: normalizeSuperParams drops the stored `tacos` switch
-- and defaults `chicken` and `korean` (off).

