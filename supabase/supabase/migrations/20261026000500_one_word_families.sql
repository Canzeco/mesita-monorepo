declare
  changed int;
begin
  update public.place_categories c
     set family_keys = v.keys
    from (values
      ('mexican', array['mexican', 'dinner']::text[]),
      ('taco', array['mexican', 'quick_bite']::text[]),
      ('japanese', array['dinner', 'sushi']::text[]),
      ('sushi', array['sushi']::text[]),
      ('ramen', array['noodles']::text[]),
      ('korean', array['korean', 'dinner']::text[])
    ) as v(slug, keys)
   where c.slug = v.slug;
  get diagnostics changed = row_count;
  if changed <> 6 then
    raise exception 'place_categories: expected 6 rows rewritten, got %', changed;
  end if;
end;
$$;

