-- MESITA-2255: Profile tags are Google's atmosphere booleans.
-- places.tags stays the dormant Mesita catalog. The Profile box reads google_tags.

alter table public.place_profiles
  add column if not exists google_tags text[] not null default '{}';

comment on column public.place_profiles.google_tags is
  'Google Places atmosphere booleans that were true, as stable slugs. The Profile tags box. places.tags is not that field.';

