-- Twenty guest families. Undefined stays, and is not a carousel.
-- A precise rail takes the type off the broader one.

create or replace function public.atlas_family_slugs_valid(slugs text[])
returns boolean
language sql
stable
set search_path = ''
as $$
  select
    slugs is not null
    and cardinality(slugs) <= 20
    and (select count(distinct x) from unnest(slugs) as x) = cardinality(slugs)
    and not ('undefined' = any(slugs) and cardinality(slugs) > 1)
    and not exists (
      select 1
      from unnest(slugs) as s
      where not exists (
        select 1 from public.place_families p
        where p.slug = s
      )
    );
$$;

