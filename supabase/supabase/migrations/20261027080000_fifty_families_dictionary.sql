--      reads the first `insert into public.place_families` in the newest
--      migration that defines the seed) and runs before any family_keys
--      write, so atlas_family_slugs_valid never sees a key that is not a
--      family yet.
--   2. catalog_membership takes the full seed printed by
--      supabase/scripts/catalog-membership-sql.ts (catalog-membership-seed
--      .test.ts pins it to the code map); place_categories, the leftover
--      Mesita slugs, take the same map (families_for_category reads them
--      first, so a shared slug like `bakery` must agree).
--   3. place_family_keys() stops preferring a stored list.
-- No app_config write: normalizeSuperParams defaults the thirty new Google
-- switches off (DEFAULT_MAP_SUPERS).

