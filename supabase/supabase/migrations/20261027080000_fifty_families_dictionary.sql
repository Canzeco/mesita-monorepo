-- dictionary of its Google categories.
--
-- Pato, 2026-10-26: "i want 50 families, not 20 or 30 … families can
-- intersect, for example, mexican and tacos kinda intersect, or bar and
-- nightclub … cover as much space with 50 Mesita Families", then "fill the
-- matrix of Google Categories vs Mesita Families", then "Mesita Families (not
-- editable, directly infered with dictionary based on canonic google
-- categories)", then "sort it in the best way for optimal UX/UI in consumer
-- app". The twenty of MESITA-2760 all stay, keys untouched; thirty join. The
-- order is a day arc — coffee to karaoke — each phase opened by its widest
-- rail (Quick, Dinner, Bar, Nightlife), Monterrey's favorites first inside it.
--
-- Families stop being a model's pick (MESITA-2827's families half): the
