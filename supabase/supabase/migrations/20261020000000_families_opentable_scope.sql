-- Tudu, is Mesita. More OpenTable scope."). A family holds places a guest
-- books a table at or orders at. Tourist attractions, museums, parks, zoos,
-- bowling, cinemas and every similar attraction move to no family
-- (`undefined`), the same list as the code twin `ATTRACTION_TYPES`
-- (`_shared/catalog-families.ts`); `catalog-families.test.ts` pins the pair.
--
-- PRIMARY FIRST. A category's `family_keys` now lists its primary family
-- first: a bakery is Sweet first, Breakfast second (it was stored the other
-- way round). The Families page keeps editing the same array.
--
-- The seed is rewritten with the same mapping so a reset on an empty table
-- writes it too; a row that already carries a valid mapping keeps it, as
-- before, which is why the rows are also updated here.

